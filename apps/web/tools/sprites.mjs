#!/usr/bin/env node
/**
 * Code-drawn sprite pipeline (track-E §6.2): assets/sprites/*.ts (palette-letter matrices) →
 *   (a) src/ui/sprites.generated.ts   rect runs per frame for the React <Sprite> (SVG, crispEdges)
 *   (b) src/ui/palette.generated.css  --px-<name> variables, day + night
 *   (c) public/game/atlas.png + atlas.json   Phaser 3 atlas (sharp rasterises, free-tex-packer packs)
 * Run: npm -w apps/web run sprites   (tsx resolves the .ts sources)
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import sharp from 'sharp'
import { packAsync } from 'free-tex-packer-core'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const { PALETTE } = await import(pathToFileURL(resolve(root, 'assets/palette.ts')).href)
const { SPRITES } = await import(pathToFileURL(resolve(root, 'assets/sprites/index.ts')).href)

const hex = (h) => [parseInt(h.slice(1, 3), 16), parseInt(h.slice(3, 5), 16), parseInt(h.slice(5, 7), 16)]

function validate (s) {
  if (s.frames.length === 0) throw new Error(`${s.name}: no frames`)
  for (const [fi, frame] of s.frames.entries()) {
    if (frame.length !== s.h) throw new Error(`${s.name} frame ${fi}: ${frame.length} rows, expected ${s.h}`)
    for (const [y, row] of frame.entries()) {
      if (row.length !== s.w) throw new Error(`${s.name} frame ${fi} row ${y}: ${row.length} columns, expected ${s.w}`)
      for (const ch of row) if (ch !== '.' && PALETTE[ch] === undefined) throw new Error(`${s.name} frame ${fi} row ${y}: '${ch}' is not in the palette`)
    }
  }
}

/** Merge horizontal runs of one colour into rects: [x, y, w, letter]. */
function runs (frame) {
  const out = []
  frame.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      const ch = row[x]
      if (ch === '.') { x++; continue }
      let w = 1
      while (x + w < row.length && row[x + w] === ch) w++
      out.push([x, y, w, ch])
      x += w
    }
  })
  return out
}

async function rasterise (s, frame) {
  const buf = Buffer.alloc(s.w * s.h * 4, 0)
  frame.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x]
      if (ch === '.') continue
      const [r, g, b] = hex(PALETTE[ch].day)
      const i = (y * s.w + x) * 4
      buf[i] = r; buf[i + 1] = g; buf[i + 2] = b; buf[i + 3] = 255
    }
  })
  return sharp(buf, { raw: { width: s.w, height: s.h, channels: 4 } }).png({ compressionLevel: 9 }).toBuffer()
}

const generated = {}
const images = []
for (const s of SPRITES) {
  validate(s)
  generated[s.name] = { w: s.w, h: s.h, fps: s.fps ?? 0, frames: s.frames.map(runs) }
  for (const [i, frame] of s.frames.entries()) images.push({ path: `${s.name}_${i}.png`, contents: await rasterise(s, frame) })
}

const ts = `// GENERATED by tools/sprites.mjs from assets/sprites/*.ts — do not edit.
export type SpriteRun = readonly [x: number, y: number, w: number, color: string]
export interface SpriteData { w: number, h: number, fps: number, frames: ReadonlyArray<ReadonlyArray<SpriteRun>> }
export const SPRITE_DATA = ${JSON.stringify(generated)} as const satisfies Record<string, SpriteData>
export type SpriteName = keyof typeof SPRITE_DATA
`
const css = `/* GENERATED by tools/sprites.mjs from assets/palette.ts — do not edit. */
:root {
${Object.values(PALETTE).map(p => `  --px-${p.name}: ${p.day};`).join('\n')}
}
:root[data-theme="night"] {
${Object.values(PALETTE).map(p => `  --px-${p.name}: ${p.night};`).join('\n')}
}
`
await mkdir(resolve(root, 'src/ui'), { recursive: true })
await writeFile(resolve(root, 'src/ui/sprites.generated.ts'), ts)
await writeFile(resolve(root, 'src/ui/palette.generated.css'), css)

const files = await packAsync(images, {
  textureName: 'atlas', width: 512, height: 512, fixedSize: false, padding: 1, allowRotation: false,
  allowTrim: false, detectIdentical: false, exporter: 'Phaser3', removeFileExtension: true, prependFolderName: false
})
await mkdir(resolve(root, 'public/game'), { recursive: true })
for (const f of files) await writeFile(resolve(root, 'public/game', f.name), f.buffer)
console.log(`sprites: ${SPRITES.length} sprites, ${images.length} frames → src/ui/sprites.generated.ts, palette.generated.css, public/game/${files.map(f => f.name).join(', ')}`)
